/**
 * One-off image prep. Not part of the build.
 *
 *   node scripts/make-images.mjs
 *
 * 1. Crops the black letterbox bars off events/warhammer-tournament.jpg (only if they are still there).
 * 2. Writes public/images/og.jpg (1200x630): the storefront photo with the store name on a royal-blue banner.
 * 3. Writes lib/content/photo-meta.generated.ts: real width/height, a tiny blur placeholder and the dominant
 *    colour for every jpg under public/images, so next/image never jumps while loading.
 *
 * sharp is not a direct dependency (next/image already uses it), so it is resolved through next.
 */
import { createRequire } from 'node:module';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const require = createRequire(import.meta.url);
const sharp = require(require.resolve('sharp', { paths: [require.resolve('next')] }));

const root = path.resolve(import.meta.dirname, '..');
const images = path.join(root, 'public', 'images');

async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else if (/\.jpg$/i.test(e.name)) out.push(p);
  }
  return out.sort();
}

// 1. Letterbox crop (bars are baked into the social-media exports). Runs once per file: it only
//    acts while the bars are still there.
for (const [rel, background] of [
  ['events/warhammer-tournament.jpg', '#000000'],
  ['store/playspace.jpg', '#ffffff'],
]) {
  const file = path.join(images, rel);
  const src = await readFile(file);
  const before = await sharp(src).metadata();
  const out = await sharp(src)
    .trim({ background, threshold: 18 })
    .jpeg({ quality: 82, mozjpeg: true })
    .toBuffer();
  const after = await sharp(out).metadata();
  if (after.height < before.height - 40) {
    await writeFile(file, out);
    console.log(
      `cropped ${rel} from ${before.width}x${before.height} to ${after.width}x${after.height}`,
    );
  }
}

// 2. og.jpg
{
  const W = 1200;
  const H = 630;
  const BANNER = 200;
  const photoH = H - BANNER;
  const photo = await sharp(path.join(images, 'storefront.jpg'))
    .resize(W, Math.round((W * 720) / 960))
    .extract({ left: 0, top: 60, width: W, height: photoH })
    .toBuffer();
  const svg = `
<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${BANNER}" viewBox="0 0 ${W} ${BANNER}">
  <rect width="${W}" height="${BANNER}" fill="#1f3f99"/>
  <rect y="0" width="${W}" height="12" fill="#121317"/>
  <rect y="12" width="${W}" height="10" fill="#f6c431"/>
  <rect y="22" width="${W}" height="6" fill="#121317"/>
  <text x="${W / 2}" y="112" text-anchor="middle" font-family="Arial Black, Impact, Helvetica, sans-serif" font-size="92" font-weight="900"
        fill="#121317" transform="translate(6 6)" letter-spacing="2">SIR GAMES-A-LOT</text>
  <text x="${W / 2}" y="112" text-anchor="middle" font-family="Arial Black, Impact, Helvetica, sans-serif" font-size="92" font-weight="900"
        fill="#f6c431" stroke="#121317" stroke-width="7" paint-order="stroke fill" letter-spacing="2">SIR GAMES-A-LOT</text>
  <text x="${W / 2}" y="168" text-anchor="middle" font-family="Helvetica, Arial, sans-serif" font-size="32" font-weight="700" fill="#ffffff">Board games · D&amp;D · Warhammer · Paints · Barrie, ON</text>
</svg>`;
  await sharp({ create: { width: W, height: H, channels: 3, background: '#1f3f99' } })
    .composite([
      { input: photo, top: 0, left: 0 },
      { input: Buffer.from(svg), top: photoH, left: 0 },
    ])
    .jpeg({ quality: 84, mozjpeg: true })
    .toFile(path.join(images, 'og.jpg'));
  console.log('wrote og.jpg');
}

// 3. metadata for next/image
{
  const entries = {};
  for (const file of await walk(images)) {
    const rel = '/images/' + path.relative(images, file).split(path.sep).join('/');
    if (rel === '/images/og.jpg') continue;
    const img = sharp(file);
    const meta = await img.metadata();
    const blur = await sharp(file).resize(10).jpeg({ quality: 40 }).toBuffer();
    const { dominant } = await sharp(file).stats();
    const hex =
      '#' +
      [dominant.r, dominant.g, dominant.b].map((v) => v.toString(16).padStart(2, '0')).join('');
    entries[rel] = {
      width: meta.width,
      height: meta.height,
      dominant: hex,
      blur: `data:image/jpeg;base64,${blur.toString('base64')}`,
    };
  }
  const body = `/* Generated by scripts/make-images.mjs. Do not edit by hand. */
export interface PhotoMeta {
  width: number;
  height: number;
  dominant: string;
  blur: string;
}

export const PHOTO_META: Record<string, PhotoMeta> = ${JSON.stringify(entries, null, 2)};
`;
  await writeFile(path.join(root, 'lib', 'content', 'photo-meta.generated.ts'), body);
  console.log(`wrote metadata for ${Object.keys(entries).length} photos`);
}
